-- ============================================================================
-- V011 — индексы зеркала сессий (change session-mirror-mcp)
-- ============================================================================
-- Отдельный файл от V010 не из бухгалтерии: построение индекса на большой
-- таблице — самостоятельная рискованная операция со своим временем блокировки,
-- и смешивать её со сменой первичного ключа значит не иметь возможности
-- остановиться между шагами. Порядок V010 → V011 обязателен: индексы строятся
-- на таблице, у которой уже есть replica_id.
--
-- Второй индекс не избыточен, а восстанавливает потерянное свойство.
-- Исходный DDL объявлял `DISTRIBUTED BY (session_key)`: в Greenplum это
-- гарантия локальности, в PostgreSQL её нет. Объявление было ложным
-- (pg_dist_partition на сервере отсутствует), поэтому `DISTRIBUTED BY` убран, а
-- вместе с ним ушла и локальность. Без индекса ни выборка сообщений сессии,
-- ни её полная перезапись при синхронизации не идут по индексу, а сканируют
-- таблицу целиком — на каждой синхронизации каждой сессии.
--
-- Уникальность на (replica_id, session_key, seq) — не гигиена, а требование:
-- пока она не выражена ограничением, «одна строка на позицию сообщения» держится
-- только на слове. Побочно она даёт возможность заменить удаление-и-вставку на
-- upsert, когда понадобится.
--
-- Совместимость: PostgreSQL 13.22 (фактическая база). Идемпотентна: IF NOT EXISTS
-- на обоих индексах, а предусловие проверяется до создания уникального.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Предварительная проверка: CREATE UNIQUE INDEX на таблице с дублями падает
-- сообщением, которое не называет ни число строк, ни способ починки. Падать
-- громко ДО создания — значит сказать оператору, что именно чинить.
-- ---------------------------------------------------------------------------
DO $precheck$
DECLARE
    duplicates bigint;
BEGIN
    SELECT count(*) INTO duplicates FROM (
        SELECT replica_id, session_key, seq
          FROM public.agent_session_messages
         GROUP BY replica_id, session_key, seq
        HAVING count(*) > 1
    ) AS duplicated_positions;

    IF duplicates > 0 THEN
        RAISE EXCEPTION
            'в agent_session_messages % позиций (replica_id, session_key, seq) '
            'встречаются более одного раза — уникальный индекс не создаётся. '
            'Дубликаты означают разорванную запись прошлого писателя (мета и '
            'сообщения писались разными транзакциями). Разберитесь ДО миграции: '
            'для зеркала безопасно удалить все строки этих сессий и дождаться '
            'следующего цикла синхронизации, который запишет их заново из JSONL',
            duplicates;
    END IF;
END
$precheck$;

-- ---------------------------------------------------------------------------
-- Сообщения сессии: канонический порядок чтения и полная перезапись сессии.
-- ---------------------------------------------------------------------------
CREATE UNIQUE INDEX IF NOT EXISTS agent_session_messages_replica_session_seq_idx
    ON public.agent_session_messages (replica_id, session_key, seq);

COMMENT ON INDEX public.agent_session_messages_replica_session_seq_idx IS
    'Канонический ключ строки сообщения и порядок чтения сессии: '
    'ORDER BY replica_id, session_key, seq. Одновременно обеспечивает '
    'не более одной строки на позицию — иначе «перезапись сессии» '
    '(DELETE + INSERT) могла бы оставить две строки на один seq.';

-- ---------------------------------------------------------------------------
-- Метаданные: очистка спрашивает «мои сессии, которых больше нет в upstream»
-- и идёт по (replica_id, updated_at); без составного индекса это полное
-- сканирование зеркала на каждом цикле.
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS agent_session_meta_replica_updated_at_idx
    ON public.agent_session_meta (replica_id, updated_at);

COMMENT ON INDEX public.agent_session_meta_replica_updated_at_idx IS
    'Рабочий индекс очистки: выборка своих сессий реплики, упорядоченная по '
    'времени изменения. Без него очистка читает всё зеркало целиком, включая '
    'чужие реплики, которые ей не принадлежат.';
