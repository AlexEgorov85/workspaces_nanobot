-- public.agent_conversation_messages_e2e — таблица из 6 строк, созданная
-- разовой проверкой очереди 2026-08-18. Она не объявлена ни в одном файле
-- sql/ (DDL очереди — create_public_agent_conversation_messages.sql и его
-- _test-клон), в коде на неё нет ни одной ссылки, и последняя запись в ней
-- старше остальных таблиц журнала на полтора месяца.
--
-- Почему отдельной миграцией, а не ручным DROP: удаление таблицы — такое же
-- изменение схемы, как её создание, и обязано быть воспроизводимо на любой
-- базе. Разовое ручное удаление оставляет после себя вопрос «откуда взялась
-- и почему исчезла», на который потом отвечает кто-то другой.
--
-- Совместимость: Greenplum 6.5 (ядро PostgreSQL 9.4) и PostgreSQL 13+.
-- Идемпотентна: IF EXISTS.
-- ============================================================================

DROP TABLE IF EXISTS public.agent_conversation_messages_e2e;
