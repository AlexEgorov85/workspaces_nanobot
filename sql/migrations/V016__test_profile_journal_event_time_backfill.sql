--
-- ЧТО ЭТО ДЕЛАЕТ И ЧТО НЕ ДЕЛАЕТ — читать первым, потому что ожидание здесь
-- обманчиво: задача формулировалась как «добавить seq и occurred_at в
-- agent_gateway_logs_test с бэкфиллом 467 строк». Ни то, ни другое не нужно и
-- невозможно, и обе ловушки стоит назвать прямо.
--
-- 1. КОЛОНКИ УЖЕ ЕСТЬ. V012 (применён 2026-10-04 13:03) добавил seq и
--    occurred_at в agent_gateway_logs_test, равно как и оба индекса
--    idx_agent_gateway_logs_test_seq / _occurred_at. Проверено в живой базе:
--    information_schema — обе колонки BIGINT/TIMESTAMPTZ при is_nullable=YES,
--    pg_indexes — оба индекса на месте. V012 закрыл ДЕФЕКТ СТРУКТУРЫ, и он
--    закрыт: пробная вставка по фиксированному списку колонок писателя
--    (db_logging_service.py:2200-2203, 14 колонок) проходит в обе таблицы,
--    seq/occurred_at записываются. Утверждение V012:11-16 «не пишется НИ ОДНА
--    строка журнала» относилось к состоянию ДО V012 и сейчас неверно.
--
-- 2. БЭКФИЛЛ 467 СТРОК НЕЧЕСТЕН, ПОТОМУ ЧТО ИСТОЧНИКА НЕТ. Все 467 строк
--    записаны ДО V012 (последняя 2026-10-02 21:38:28, V012 применён
--    2026-10-04 13:03; строк после V012 — ноль), и ни в одной из них ключа нет:
--    metadata ? 'seq' → 0, metadata ? 'occurred_at' → 0 (186 строк имеют
--    metadata = {}, остальные — посторонние ключи: latency_ms, tool_call_id,
--    usage, model…). Восстановить нечего.
--
--    Почему нельзя досочинить из "timestamp": это момент ЗАПИСИ строки
--    (DEFAULT CURRENT_TIMESTAMP), а seq/occurred_at — момент СОБЫТИЯ. Именно их
--    различие и является смыслом двух колонок (см. комментарий колонки в
--    create_public_agent_gateway_logs.sql). Присвоение
--    occurred_at := "timestamp" сделало бы колонки тождественными по
--    построению и навсегда уничтожило бы возможность отличить одно от
--    другого — это выдуманный факт, ровно того класса, который эта семья
--    изменений снимает (f7e4a8d убрал выдуманный UUID по той же причине).
--    Синтезировать seq как «номер строки по порядку timestamp/id» тоже нельзя:
--    seq объявлен как event-time в наносекундах (time.time_ns()), и
--    синтетический счётчик перемешался бы с настоящими значениями будущих
--    строк МОЛЧА — худший вид расхождения.
--
--    Правило V008, которое здесь воспроизводится дословно: «Копирует УЖЕ
--    СУЩЕСТВУЮЩИЙ ключ из metadata и ничего не выдумывает: придуманный момент
--    события неотличим от настоящего». На боевой таблице этот же предикат
--    дал 0 строк — по той же причине.
--
-- 3. NULL — ЭТО ОБЪЯВЛЕННОЕ СОСТОЯНИЕ, А НЕ НЕДОДЕЛКА. Комментарий колонки
--    seq: «NULL означает "момент события неизвестно" и НЕ "собылось позже
--    всего": такие строки читаются отдельным счётчиком unattributed».
--    V012 объявил колонки nullable НАМЕРЕННО, «контракт чтения оборота без
--    ключа порядка должен оставаться представимым». Стирать этот контракт
--    заполнением значило бы уничтожить ровно то представимое состояние,
--    ради которого nullable и оставлен.
--
-- ЧТО ДЕЛАЕТ ЭТА МИГРАЦИЯ:
--   * обеспечивает наличие колонок (идемпотентно, через каталог — на ядре
--     Greenplum 9.4 нет ADD COLUMN IF NOT EXISTS);
--   * переносит ключ из metadata ТОЧНО по предикату V008 (на этих данных
--     затрагивает 0 строк; на среде, где строки писались между переходом
--     писателя и миграцией, — заполнит их);
--   * ОГЛАВЛЯЕТ остаток: считает строки без ключа и печатает их число, чтобы
--     «467 строк без момента события» было объявленным и посчитанным
--     состоянием, а не тихой дырой.
--
-- ЧТО НЕ ДЕЛАЕТ:
--   * НЕ удаляет строки. Шаг 3 V008 (DELETE WHERE seq IS NULL) не
--     воспроизводится: он требует явной авторизации оператора
--     (SET nanobot.cleanup_rows_without_seq = 'on') и является решением о
--     данных, а не о схеме. Владелец на 2026-10-04 решил ничего не удалять.
--   * НЕ наводит NOT NULL. ALTER COLUMN ... SET NOT NULL запрещён в новых
--     миграциях стражем tests/test_runtime_environment_contract.py (на ядре
--     Greenplum 9.4 это полное сканирование таблицы под ACCESS EXCLUSIVE).
--     Колонки тест-профиля остаются nullable СОЗНАТЕЛЬНО — как и объявлено в
--     V012 и в DDL клона. Это расхождение с боевой таблицей (где NOT NULL стоит
--     после V008) объявлено, а не случайно.
--   * НЕ трогает боевую таблицу agent_gateway_logs.
--
-- Совместимость: Greenplum 6.5 (ядро PostgreSQL 9.4) и PostgreSQL 13+.
-- Идемпотентна: повторное применение — no-op (предикат UPDATE срабатывает
-- только на строках, где ключ ещё не перенесён).
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. Колонки — на случай среды, где V012 не применялся. Проверка каталога,
--    а не IF NOT EXISTS: на 9.4 его нет.
-- ---------------------------------------------------------------------------
DO $columns$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name   = 'agent_gateway_logs_test'
          AND column_name  = 'seq'
    ) THEN
        ALTER TABLE public.agent_gateway_logs_test ADD COLUMN seq BIGINT;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name   = 'agent_gateway_logs_test'
          AND column_name  = 'occurred_at'
    ) THEN
        ALTER TABLE public.agent_gateway_logs_test ADD COLUMN occurred_at TIMESTAMPTZ;
    END IF;
END
$columns$;

-- ---------------------------------------------------------------------------
-- 2. Перенос УЖЕ СУЩЕСТВУЮЩЕГО ключа из metadata. Предикат V008 без
--    изменений: обе строки в метаданных, seq — целое, occurred_at — ISO-8601.
--    Порядок по timestamp НЕ используется: это момент записи, а не события.
-- ---------------------------------------------------------------------------
UPDATE public.agent_gateway_logs_test
   SET seq         = (metadata->>'seq')::bigint,
       occurred_at = (metadata->>'occurred_at')::timestamptz
 WHERE seq IS NULL
   AND metadata IS NOT NULL
   AND metadata ? 'seq'
   AND (metadata->>'seq') ~ '^[0-9]+$'
   AND metadata ? 'occurred_at'
   AND (metadata->>'occurred_at') ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(\.[0-9]+)?(Z|[+-][0-9]{2}:[0-9]{2})$';

-- ---------------------------------------------------------------------------
-- 3. Оглашение остатка. НЕ исключение: остаток без ключа — законное
--    состояние тест-профиля, и падать на нём означало бы запретить миграции
--    в среду, где таких строк нет вовсе. Число печатается, чтобы состояние
--    читалось, а не подразумевалось.
-- ---------------------------------------------------------------------------
DO $report$
DECLARE
    total      bigint;
    unattributed bigint;
BEGIN
    IF to_regclass('public.agent_gateway_logs_test') IS NULL THEN
        RAISE NOTICE 'тест-журнал отсутствует — шаг пропущен';
        RETURN;
    END IF;

    SELECT count(*) INTO total FROM public.agent_gateway_logs_test;

    SELECT count(*) INTO unattributed
      FROM public.agent_gateway_logs_test
     WHERE seq IS NULL OR occurred_at IS NULL;

    IF unattributed = 0 THEN
        RAISE NOTICE 'тест-журнал: % строк, ключ порядка и момент события заполнены у всех', total;
    ELSE
        RAISE NOTICE
            'тест-журнал: % строк, из них % без ключа порядка/момента события. '
            'Это не недоделка: ключа нет и в metadata (проверено), восстановить '
            'нечего, удаление строк не авторизовано. Такие строки читаются '
            'счётчиком unattributed, а заполнять их моментом ЗАПИСИ значило бы '
            'подделать момент события.', total, unattributed;
    END IF;
END
$report$;
