-- ============================================================================
-- V009 — индексы под момент события и ключ порядка
--
-- Порядок обязателен: индексы создаются ПОСЛЕ backfill и очистки V008.
-- До очистки это были бы индексы по колонке, где NULL держит 10 % строк
-- (те самые 48 979 строк, критерий очистки — «нет ключа»), то есть
-- планировщик всё равно выбирал бы seqscan, а индексы только занимали
-- место и обслуживались при каждой вставке.
--
-- Зачем оба:
--   * seq — канонический порядок чтения оборота, ORDER BY seq, id.
--     Без него чтение оборота сортирует всё, что попало в окно.
--   * occurred_at — окно времени события. Существующий
--     agent_gateway_logs_user_id_timestamp_idx стоит на "timestamp", то
--     есть на моменте ЗАПИСИ строки (его ставит база при сбросе батча).
--     Для канонического окна времени он не подходит по определению, и
--     поэтому его удаление — отдельное решение по замеренной
--     селективности (требование «Индексы журнала»), а не следствие этой
--     миграции.
--
-- Обычные btree, не индексы-выражения: решение о хранении момента
-- события в колонке принято замером, и выражение по metadata->>'seq'
-- STABLE-зависимо от часового пояса, то есть не индексируется вовсе.
--
-- Идемпотентна: IF NOT EXISTS. Повторный прогон — no-op.
-- ============================================================================

CREATE INDEX IF NOT EXISTS idx_agent_logs_seq
    ON public.agent_gateway_logs (seq);

CREATE INDEX IF NOT EXISTS idx_agent_logs_occurred_at
    ON public.agent_gateway_logs (occurred_at DESC);

COMMENT ON INDEX public.idx_agent_logs_seq IS
    'Обслуживает канонический порядок чтения оборота: ORDER BY seq, id. seq — момент события в наносекундах, единственный порядок, который не разъезжается с id при сортировке.';

COMMENT ON INDEX public.idx_agent_logs_occurred_at IS
    'Обслуживает окно времени СОБЫТИЯ. "timestamp" для этого не годится: он ставится базой при сбросе батча, и в пределах одной пачки все строки получают одну отметку, поэтому окно по нему не является окном события.';
