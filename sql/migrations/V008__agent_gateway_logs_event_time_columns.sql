-- ============================================================================
-- V008 — agent_gateway_logs.seq / .occurred_at (change 2026-10-02-journal-observability)
-- ============================================================================
-- Переносит момент СОБЫТИЯ и выживаемый ключ ПОРЯДКА из JSONB в настоящие
-- колонки. Выбор хранилища сделан ЗАМЕРОМ, а не вкусом: на 48 979 боевых
-- строках колонка выиграла 3 сценария из 3 (0.242 против 0.384 мс; 0.197
-- против 0.275 мс; 5.548 против 5.905 мс) — см. openspec/specs/logging-db/spec.md,
-- требование «Хранение момента события и идентификатора оборота выбрано
-- замером плана запроса». JSONB отпадает и по существу:
-- (metadata->>'occurred_at')::timestamptz не индексируется (текст→timestamptz
-- это STABLE, а индекс требует IMMUTABLE), а сортировка ISO-строкой не
-- сохраняет хронологию ('...33.261Z' встаёт после '...33.261000Z').
--
-- ТРАНСПОРТ НЕ МЕНЯЕТСЯ: оба значения по-прежнему едут в metadata внутри
-- батча — только так они переживают батчирование и обоих писателей, — и
-- разбирает их в колонки единственный табличный писатель.
--
-- ПОРЯДОК ШАГОВ ОБЯЗАТЕЛЕН: nullable-колонки → backfill → очистка строк без
-- ключа → SET NOT NULL. Обратный порядок ломает существующие строки:
-- SET NOT NULL до backfill падает на них, а backfill после него невозможен
-- (ограничение не даёт оставить NULL там, где ключа нет) и превращает
-- «момент неизвестен» в отказ записи всей партии.
--
-- Шаг 3 (очистка) УБИВАЕТ ДАННЫЕ и выполняется только по явному решению
-- оператора: спецификация удаление исторических логов не авторизует, объём
-- определяется замером ДО операции, а операция отчитывается числом удалённых
-- строк. Пока флаг не выставлен, шаг не выполняется — и тогда шаг 4 падает
-- на строках без ключа, что лучше молчаливого удаления 48 979 строк.
--
-- Совместимость: PostgreSQL 13.22 (фактическая база; служебная таблица
-- pg_dist_partition на сервере отсутствует). Синтаксиса распределённой СУБД
-- здесь нет и быть не должно — guard-тест падает на его появлении.
-- Идемпотентна: ADD COLUMN IF NOT EXISTS + UPDATE с предикатом + ALTER
-- с IF EXISTS-эквивалентом (ограничение ставится IF NOT EXISTS-повторно
-- только при отсутствии, см. шаг 4).
--
-- ВНИМАНИЕ: этот файл НЕ применяется к боевой базе в рамках change
-- 2026-10-02-journal-observability (DDL применяется только к тестовому
-- профилю; правка боевой схемы — отдельный заход с бэкапом). Регистрация
-- версии выполняется runner'ом tools/migrate.py (INSERT в
-- public.schema_migrations) — НЕ этим файлом.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Шаг 1 — колонки nullable. Иначе существующие строки ломают шаг.
-- ---------------------------------------------------------------------------
ALTER TABLE public.agent_gateway_logs
    ADD COLUMN IF NOT EXISTS seq         BIGINT,
    ADD COLUMN IF NOT EXISTS occurred_at TIMESTAMPTZ;

COMMENT ON COLUMN public.agent_gateway_logs.seq IS
    'Ключ порядка строки журнала: момент события в наносекундах '
    '(time.time_ns()), выживаемый при шаге часов назад полом монотонности. '
    'Канонический порядок чтения оборота — ORDER BY seq, id. NULL означает '
    '''момент события неизвестно'' и НЕ ''собылось позже всего'': такие строки '
    'читаются отдельным счётчиком unattributed. Ставит писатель (DbLoggingService '
    'или операция log_events платформы), а не база.';

COMMENT ON COLUMN public.agent_gateway_logs.occurred_at IS
    'Момент СОБЫТИЯ (не записи: timestamp остаётся моментом сброса батча). '
    'Тот же мгновенный снимок, что и seq, — два независимых now() разошлись бы. '
    'Сортировка и окно времени берутся по этой колонке: текстовая копия в '
    'metadata (metadata->>''occurred_at'') остаётся читаемой копией для '
    'человека, но как хронология не сортируется и не индексируется.';

-- ---------------------------------------------------------------------------
-- Шаг 2 — backfill. Копирует УЖЕ СУЩЕСТВУЮЩИЙ ключ из metadata и ничего
-- не выдумывает: придуманный момент события неотличим от настоящего.
-- На данных замера (2026-10-02) затрагивает 0 строк — ключа нет ни в одной;
-- он нужен для строк, записанных между переходом писателя и миграцией.
-- ---------------------------------------------------------------------------
UPDATE public.agent_gateway_logs
   SET seq         = (metadata->>'seq')::bigint,
       occurred_at = (metadata->>'occurred_at')::timestamptz
 WHERE seq IS NULL
   AND metadata IS NOT NULL
   AND metadata ? 'seq'
   AND (metadata->>'seq') ~ '^[0-9]+$'
   AND metadata ? 'occurred_at'
   AND (metadata->>'occurred_at') ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(\.[0-9]+)?(Z|[+-][0-9]{2}:[0-9]{2})$';

-- ---------------------------------------------------------------------------
-- Шаг 3 — очистка строк без ключа. Критерий — ОТСУТСТВИЕ КЛЮЧА (seq IS NULL),
-- а не имя события: по замеру строк без ключа 48 979, из них 2 426 с
-- metadata IS NULL восстановить нечем. Ключа нет ни в колонке, ни в metadata —
-- значит его неоткуда взять, и такая строка удаляется, а не достраивается.
--
-- Флаг nanobot.cleanup_rows_without_seq выставляет оператор:
--     SET nanobot.cleanup_rows_without_seq = 'on';
-- Без него шаг пропускается (RAISE NOTICE) и следующий шаг падает — это
-- громкий отказ вместо молчаливого удаления истории.
-- ---------------------------------------------------------------------------
DO $cleanup$
DECLARE
    deleted bigint;
BEGIN
    IF current_setting('nanobot.cleanup_rows_without_seq', true) IS DISTINCT FROM 'on' THEN
        RAISE NOTICE
            'шаг 3 (очистка строк без seq) ПРОПУЩЕН: требуется '
            'SET nanobot.cleanup_rows_without_seq = ''on''; шаг 4 упадёт на строках без ключа';
        RETURN;
    END IF;

    DELETE FROM public.agent_gateway_logs WHERE seq IS NULL;
    GET DIAGNOSTICS deleted = ROW_COUNT;
    RAISE NOTICE 'очищено строк без ключа порядка: %', deleted;
END
$cleanup$;

-- ---------------------------------------------------------------------------
-- Шаг 4 — ограничение. ТОЛЬКО после backfill и очистки. До них оно ломает
-- миграцию: NOT NULL на строках без ключа. Проверка нулевой остачи сделана
-- явно и ДО ограничения, чтобы падение называло причину, а не «violates
-- not-null constraint».
-- ---------------------------------------------------------------------------
DO $verify$
DECLARE
    leftover bigint;
BEGIN
    SELECT count(*) INTO leftover FROM public.agent_gateway_logs WHERE seq IS NULL;
    IF leftover > 0 THEN
        RAISE EXCEPTION
            'осталось % строк без ключа порядка (seq IS NULL): очистка не выполнена или выполнена не полностью. '
            'SET NOT NULL не применяется — выставите nanobot.cleanup_rows_without_seq=''on'' и повторите',
            leftover;
    END IF;
END
$verify$;

ALTER TABLE public.agent_gateway_logs
    ALTER COLUMN seq SET NOT NULL;

ALTER TABLE public.agent_gateway_logs
    ALTER COLUMN occurred_at SET NOT NULL;
