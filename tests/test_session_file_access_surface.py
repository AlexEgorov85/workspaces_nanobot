"""Поверхность доступа к файлам: что закрыто намеренно, а что осталось открытым.

Смена `2026-10-03-session-files` закрыла три пути, через которые модель могла
создать или прочитать файл мимо папки сессии: шелл (`tools.exec`), запуск
установленных CLI-приложений (`tools.cliApps`) и чтение произвольного пути
хоста проектным инструментом (`document_read`).

Осталась одна щель, и она **закрыта решением, а не недосмотром**: штатный
`read_file` продолжает читать по абсолютному пути. Причина в том, что встроенная
граница (`tools.restrictToWorkspace`) опирается на `agents.defaults.workspace` —
`~/.nanobot/workspace`, а это **подкаталог** репозитория, который агент
обслуживает. Поднять границу на этот корень значит отрезать агента от `lib/`,
`config.py`, `mcp-platform/`, `tests/`, `docs/`, `sql/`, то есть от его работы.

Тест существует, чтобы решение не стало тихим:

* пока корень границы — подкаталог обслуживаемого репозитория, поверхность
  остаётся как есть, и тест фиксирует это явно;
* если однажды корень границы перестанет быть подкаталогом (то есть его можно
  будет поднять без вреда), тест **упадёт** с указанием, что границу пора
  включать. Смена обоснования обязана ломать этот тест, а не проходить молча.

Проверки `exec`/`cliApps` — карантин наоборот: их включение возвращает два пути
исполнения кода, поэтому флаги закреплены как `false` осознанно.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _settings() -> dict:
    with (ROOT / "config.json").open(encoding="utf-8") as handle:
        return json.load(handle)


def test_shell_and_cli_apps_are_off() -> None:
    """Обхода через исполнение кода не осталось: обе двери закрыты."""
    tools = _settings()["tools"]
    assert tools["exec"]["enable"] is False, (
        "tools.exec вернулся: модель снова может исполнить команду, а это "
        "единственный обход границы файлов, который не закрывается хуком"
    )
    assert tools["cliApps"]["enable"] is False, (
        "tools.cliApps вернулся: это второй путь исполнения кода, он остаётся "
        "незакрытым вместе с включённым шеллом"
    )


def test_workspace_boundary_root_is_a_subdirectory_of_the_served_repo() -> None:
    """Корень встроенной границы — подкаталог обслуживаемого репозитория.

    Пока это так, границу поднимать нельзя. Тест падает, как только условие
    перестаёт выполняться, и говорит, что делать.
    """
    declared = _settings()["agents"]["defaults"]["workspace"]
    workspace = Path(declared).expanduser()

    assert workspace.is_dir(), f"рабочий каталог агента не найден: {workspace}"
    assert workspace != ROOT and workspace.is_relative_to(ROOT), (
        f"корень встроенной границы ({workspace}) больше не подкаталог "
        f"репозитория ({ROOT}) — значит границу можно поднять, не отрезав "
        "агента от его кода. Включи tools.restrictToWorkspace и удали "
        "обоснование про остаточную поверхность чтения из спеки "
        "runtime/session-files"
    )

    # Обслуживаемый код лежит рядом с рабочим каталогом, а не внутри него.
    assert not (workspace / "lib").exists() and (ROOT / "lib").is_dir(), (
        "ожидалось, что обслуживаемый код лежит вне рабочего каталога агента; "
        "если это изменилось, перечитай решение о границе"
    )


def test_builtin_read_file_surface_is_a_decision_not_an_accident() -> None:
    """Остаточная поверхность чтения объявлена, а не выдана за границу."""
    tools = _settings()["tools"]
    assert tools["restrictToWorkspace"] is False, (
        "встроенная граница включена — значит запись в папку сессии и чтение "
        "из репозитория ограничены корнем рабочего каталога, и объявление "
        "остаточной поверхности чтения в спеке runtime/session-files надо "
        "переписать"
    )
