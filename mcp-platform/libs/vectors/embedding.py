"""Контракт эмбеддера, а не его реализация.

Портировано из агента: ``lib/services/cache_provider_impl.py::get_embedding``
(миграция ``enterprise-mcp-platform``, фаза 3). Удаление агентской копии —
фазы 4/5/9; портировано поведение, но не место HTTP-вызова.

**Здесь больше нет ни ``httpx``, ни ``requests``, ни эндпойнта.** HTTP-вызов
провайдера — разделяемый ресурс, и его владелец — ``libs/llm``. Владелец
FAISS-индексов не должен поднимать сетевой клиент: вторая копия клиента = вторые
соединения, своя сессия, своя логика ретраев, минуя владельца. Правило 8
README проверяется стражем, и ``libs/vectors`` проходит его именно потому, что
вызова провайдера здесь нет.

Остаётся один тип — ``Embedder`` — и правило подключения: эмбеддер
подставляется владельцем индекса сверху, а его реализация берётся у сервиса
capability ``llm`` из контейнера (см. ``VectorIndexOwner(embed=...)`` и
адаптер в ``capabilities/vectors/service/main.py``).

Модуль без зависимостей: его можно заменить, не трогая ни индексы, ни capability.
"""

from __future__ import annotations

from collections.abc import Callable

#: Колбэк эмбеддера: ``(text) -> list[float] | None``.
#:
#: ``None`` означает «эмбеддер не ответил» — сбой инфраструктуры, а не «ничего
#: не найдено». Владелец индекса обязан различать эти случаи: пустая выдача от
#: недоступного эмбеддера выглядела бы как «в базе нет подходящих документов».
Embedder = Callable[[str], list[float] | None]
