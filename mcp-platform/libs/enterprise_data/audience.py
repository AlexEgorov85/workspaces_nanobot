"""Имена аудиторий вызова — единственное место, где они определены.

Аудитория отвечает на вопрос «кто инициировал работу», и на этом
основании у неё ровно два значения:

- ``model`` — то, что видит агент: вызовы инструментов модели, включая
  работу навыков. Позже навыки начнут ходить в PostgreSQL, и это тот
  класс, который ограничивается;
- ``runtime`` — внутренние потоки процесса платформы: путь оборота
  канала, запись журнала, зеркало сессии, обслуживание очереди задач.

Определение обязано быть одно. Раньше эти два имени жили в
``servers/enterprise/capabilities/data/service/main.py``, откуда их
импортировали tool'ы capability, и пул, который ими пользуется, не мог
до них дотянуться: общий код не имеет права зависеть от capability.
Отсюда модуль в ``libs/enterprise_data`` — на уровне, доступном и пулу,
и capability.

Объявление живёт здесь, а классификация конкретных операций — в
``servers/enterprise/capabilities/data/service/registry.py``: пулу
известно, какие бывают аудитории, а какая операция к какой относится,
знать не его дело.
"""

from __future__ import annotations

#: Работа инициирована моделью или навыком по поручению модели.
JOB_AUDIENCE_MODEL: str = "model"

#: Работа инициирована внутренним потоком процесса платформы.
JOB_AUDIENCE_RUNTIME: str = "runtime"

#: Все известные аудитории. Секция ``job_classes`` в ``platform.json``
#: обязана объявлять настройки ровно для этих имён: лишний ключ означает,
#: что кто-то заявил настройки для несуществующей аудитории, а
#: недостающий — что у аудитории нет ни потолка времени, ни предела
#: ожидания, то есть она может занять место навсегда.
ALL_AUDIENCES: frozenset[str] = frozenset(
    {JOB_AUDIENCE_MODEL, JOB_AUDIENCE_RUNTIME}
)
