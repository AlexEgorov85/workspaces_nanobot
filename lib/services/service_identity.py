"""Служебные личности компонентов агента — один список на проект.

Зачем этот модуль. У канала и фоновой службы пользователя нет, и личности у
них быть не может по построению. Но платформа требует личность у каждого
вызова, и раньше на всех стоял один ``SERVICE_USER = "gateway"``. По журналу
было не видно, кто что делал: замер показал 97,6 % строк журнала подписаны
одним и тем же именем, и служебная активность выглядела как работа человека.

Теперь своё имя у каждого компонента. Это не украшение: подпись служебной
активности своим именем — единственный способ отличить ``session-mirror`` от
``queue-worker`` в разборе, а разбираться приходится именно там, где что-то
сломалось.

Почему имена, а не один ``service``: платформа пока требует у вызова все три
ключа (``workspaces/request_id``, ``workspaces/session_id``,
``workspaces/user_id``), и отказ по этому контракту — это
``identity_missing`` на каждом старте. Служебному вызову, у которого сессии
нет вовсе (чистка журнала, уведомление компаундера), до тех пор приходится
давать СЛУЖЕБНУЮ сессию из ``SERVICE_SESSION_*``, а не сессию пользователя.
Подставить чужую нельзя: у платформы это означало бы «прибери эту сессию».

Когда контракт платформы научится отличать служебную личность от
пользовательской явно, ``SERVICE_SESSION_*`` и требование ``session_id``
исчезнут, а этот модуль останется — он и есть объявление имён.

Префикс ``service:`` в служебных сессиях выбран так, чтобы не пересечься с
пользовательскими, которые устроены как ``<канал>:<чат>`` (``postgres:chat_alice_1``).
Пользовательской сессии с каналом ``service`` не существует, а если
появится — столкновение будет заметно, а не растворится в общем молчании.
"""

#: Писатель журнала: ``log_events``, ``upsert_question_run``, ``purge_logs``.
#: До появления этого модуля он не передавал личность ВООБЩЕ, и ``purge_logs``
#: отвергался с ``identity_missing`` на каждом старте процесса.
JOURNAL_WRITER = "journal"

#: Опросчик очереди задач (``lib/channels/queue_ops.py``).
QUEUE_WORKER = "queue-worker"

#: Зеркало сессий (``lib/gateway/mirror/mirror_poller.py``).
SESSION_MIRROR = "session-mirror"

#: Проба платформы при старте и восстановлении (``lib/gateway/mcp_health.py``).
MCP_HEALTH = "mcp-health"

#: Запись и чтение файлов сессии (``lib/services/session_files.py``).
SESSION_FILES = "session-files"

#: Служебные сессии для вызовов, у которых пользовательской сессии нет.
#: Именно поэтому и только до смены контракта платформы.
SERVICE_SESSION_JOURNAL = "service:journal"
SERVICE_SESSION_COMPACTOR = "service:compactor"

#: Все имена разом — страж сверяет, что ни одна копия константы в коде не
#: разошлась с этим списком, а новое имя не завели мимо него.
SERVICE_IDENTITIES = frozenset({
    JOURNAL_WRITER,
    QUEUE_WORKER,
    SESSION_MIRROR,
    MCP_HEALTH,
    SESSION_FILES,
})
