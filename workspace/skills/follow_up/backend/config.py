"""
Follow Up 2.0 — Configuration via Pydantic Settings.
Читает переменные из .env файла и окружения.
"""
from __future__ import annotations
from pathlib import Path
from typing import Literal, List, Optional
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    # Два файла, поздний перекрывает ранний. `site_defaults.env` — значения
    # нашей площадки: адрес Greenplum, схемы, витрины, репозитории. Лежит
    # только в нашем приватном репозитории. Код навыка уходит в публичный
    # репозиторий нанобота без этого файла, и там всё то же самое берётся из
    # настроек агента (`core/nanobot_config.adopt_agent_gp`). Поэтому ниже
    # у внутренних полей нейтральные значения по умолчанию: адресов площадки
    # в коде нет вовсе.
    model_config = SettingsConfigDict(
        env_file=("site_defaults.env", ".env"),
        env_file_encoding="utf-8",
        extra="ignore",
        case_sensitive=False,
    )

    # ──────────────────────────────────────────────────────────────
    # LLM
    # ──────────────────────────────────────────────────────────────
    llm_mode: Literal["local", "api", "gigachat"] = "api"
    """
    'api'      — внешний OpenAI-compatible endpoint (Fireworks, OpenAI и т.д.) — DEFAULT
    'gigachat' — GigaChat через внутренний API (прод банка)
    'local'    — vLLM на GPU-машине (опция, если есть инфраструктура)
    """
    llm_base_url: str = "https://api.fireworks.ai/inference/v1"
    llm_api_key: str = "EMPTY"
    llm_model_name: Optional[str] = None   # None → автоопределение с /models
    llm_max_tokens: int = 2000
    llm_temperature: float = 0.1

    # Отдельная модель для извлечения отклонений при индексации.
    # Это разовая операция → можно использовать модель помощнее (70B) даже если
    # для чата стоит 8B ради скорости. None → берётся llm_model_name.
    llm_extractor_model: Optional[str] = None

    # На чём считать bge-m3 и реранкер: "auto" | "cpu" | "cuda".
    # "auto" берёт GPU, если она видна, — и это опасный дефолт там, где
    # рядом работает vLLM. На машине нанобота (DataLab, две карты) он
    # поднят с --gpu-memory-utilization 0.8, то есть свободного остаётся
    # пятая часть; наши три гигабайта туда лезут молча и роняют не нас, а
    # LLM всего подразделения. Причину такого падения ищут где угодно,
    # только не в соседнем навыке. Рядом с vLLM ставить "cpu".
    models_device: Literal["auto", "cpu", "cuda"] = "auto"

    # Когда regex уже уверенно классифицировал intent — не звать LLM в Query Understanding
    qu_skip_llm_when_quick_classified: bool = True

    # Таймаут одного LLM-запроса (сек). Без него зависший вызов
    # блокирует SSE-карточку навсегда
    llm_request_timeout: int = 180

    # GigaChat (внутренняя сеть)
    gigachat_api_url: Optional[str] = None    # GIGACHAT_API_URL env
    gigachat_access_token: Optional[str] = None  # JPY_API_TOKEN env
    gigachat_model: str = "GigaChat-3-Ultra"
    gigachat_delay: float = 9.0  # Rate limiter delay (сек). Для внутренней сети банка — 8-9с

    # Межвызовный интервал очереди к модели (сек). Пусто — вывести из режима:
    # у GigaChat это `gigachat_delay` (лимит провайдера на пользователя), у
    # локальной модели интервала нет вовсе.
    #
    # Разница не косметическая. У нанобота на DataLab модель своя — vLLM с
    # Qwen3-14B на двух картах, и никакого лимита на обращения там нет:
    # очередь держит сам сервер. Девять секунд между вызовами превратились
    # бы в 27 секунд чистого ожидания на ход (потолок — три вызова) на
    # ровном месте.
    llm_min_interval_sec: Optional[float] = None

    # Не брать модель у агента, даже когда нас запустил нанобот. Аварийный
    # тумблер: обычно наоборот — администратор меняет модель в одном месте,
    # и за ней идут все навыки (как у audit_analyzer).
    llm_ignore_nanobot: bool = False

    # ──────────────────────────────────────────────────────────────
    # Идентичность проверки (КМ) — backend/core/identity.py
    # ──────────────────────────────────────────────────────────────
    # Справочник существующих КМ собирается из трёх источников (локальный
    # SQLite, корпус GP, витрина пунктов актов). TTL держит его свежим, не
    # заставляя ходить в GP на каждый вопрос.
    identity_registry_ttl_sec: int = 60
    # Точное сравнение check_id вместо ILIKE в репозиториях. false —
    # аварийный откат к прежнему поведению: аудит значений идёт на
    # прод-данных, которых у разработчика на машине нет. Снимается вместе
    # с отчётом аудита (docs/AGENT_ARCHITECTURE_PLAN.md, ЭТАП 0 п.6).
    identity_exact_match: bool = True

    # ──────────────────────────────────────────────────────────────
    # Физика исполнения (ЭТАП 1): очередь к модели, CPU, запись
    # ──────────────────────────────────────────────────────────────
    # Жёсткий дедлайн диалогового хода. Раньше его не было вовсе:
    # `while not task.done()` в chat.py крутился, пока не отвалится клиент,
    # а llm_request_timeout=180 с двумя ретраями давал до девяти минут.
    # 150 с = 2 вызова по профилю frame (90 с) с запасом на локальную работу.
    turn_deadline_sec: float = 150.0
    # Максимальная длина одного CPU-среза. Между срезами проверяется отмена,
    # поэтому это же — верхняя граница времени реакции на «Стоп».
    # 2 с ≈ 26 пар кросс-энкодера при замеренных 13 парах/с.
    cpu_slice_max_sec: float = 2.0
    # Сколько секунд бездействия аудитора считать «можно грузить CPU фоном».
    # Меньше — гидратация чаще уступает; больше — реже просыпается.
    background_idle_sec: float = 30.0
    # Таймаут общего лока записи SQLite. Превышение — это баг сериализации
    # (кто-то держит транзакцию размером с батч), а не повод ждать дальше.
    db_write_lock_timeout_sec: float = 30.0
    # Не запускать фоновых писателей, если файлом БД владеет другой живой
    # процесс или не прошла проверка целостности при старте.
    db_startup_integrity_check: bool = True

    # ──────────────────────────────────────────────────────────────
    # Память диалога (ЭТАП 3)
    # ──────────────────────────────────────────────────────────────
    # Сколько ходов сессии замороженный вопрос считается живым. Прецедент:
    # письма карточки живут 2 часа — это единственное состояние сессии, у
    # которого сегодня вообще есть срок.
    open_question_ttl_turns: int = 2
    open_question_ttl_sec: float = 1800.0
    # Сколько ходов держится подставленный фокус, прежде чем перестать
    # подставляться молча. Провенанс `user_said` не истекает: аудитор назвал
    # номер сам, и забывать это раньше времени — снова терять контекст.
    focus_inferred_ttl_turns: int = 6

    # ──────────────────────────────────────────────────────────────
    # Критик достаточности (ЭТАП 4)
    # ──────────────────────────────────────────────────────────────
    # Потолок вызовов модели на ход, включая ретраи. Слот стоит 9 с
    # межвызовного интервала: четвёртый вызов — это минута ожидания.
    turn_max_llm_calls: int = 3
    # Бесплатные заходы: расширить порог и сменить режим. Оба локальные,
    # но повторять их бесконечно значит тратить время аудитора впустую.
    critic_max_widen: int = 1
    critic_max_switch: int = 1
    # Минимальная заполненность поля, по которому фильтровали. Ниже — ответ
    # опирается на данные, которых почти нет, и это надо сказать.
    critic_min_field_fill: float = 0.30
    # Взвешенное по IDF покрытие содержательных термов вопроса найденным.
    # Порог калибруется на офлайн-наборе (ЭТАП 5).
    critic_min_term_coverage: float = 0.35
    # Содержательность терма = его IDF не ниже доли от среднего по корпусу.
    critic_terms_idf_floor: float = 0.8
    # Сигналы релевантности МЕНЯЮТ вердикт. На ЭТАПЕ 4 выключено: пороги ещё
    # не калиброваны, и блокировать ответы по некалиброванному порогу хуже,
    # чем считать сигнал и писать в журнал. Включается на ЭТАПЕ 5.
    critic_relevance_enforced: bool = False
    # Новое ядро включается СНАЧАЛА только для интентов, которые сегодня и так
    # деградируют: KM_DETAIL падал, остальные три отвечают пятью чанками.
    # Регрессия ограничена по построению — хуже сломанного не станет.
    core_enabled_intents: str = "KM_DETAIL,FOLLOWUP,ANALYTICS,GENERAL"
    core_enabled: bool = True

    # ──────────────────────────────────────────────────────────────
    # Режимы поиска (ЭТАП 2)
    # ──────────────────────────────────────────────────────────────
    # Потолок числа актов в охватном ответе. Реранк 30 пар при замеренных
    # 13 парах/с — 2.3 с; больше на единственном процессоре неоправданно,
    # а аудитору список длиннее тридцати всё равно нечитаем.
    coverage_max_docs: int = 30
    # Минимальное косинусное сходство для попадания акта в охват. Порог
    # калибруется на офлайн-наборе (ЭТАП 5): ниже — шум, выше — теряются
    # акты, где тема названа другими словами.
    coverage_min_score: float = 0.30
    # Сколько пар отдавать кросс-энкодеру за раз. 24 × (1/13 с) ≈ 1.8 с —
    # в пределах cpu_slice_max_sec, то есть отмена доходит вовремя.
    rerank_batch_pairs: int = 24
    # Фрагментов одного акта, уходящих в ответ. Шести не хватало: на вопрос
    # «что было в акте» модель видела только начало документа и честно
    # отвечала, что перечня там нет. Двенадцать фрагментов — это ~18 тыс.
    # символов, которые контекст ответа (14 тыс.) сам подрежет по приоритету.
    read_document_top_n: int = 12
    # Порог близости описания отклонения к теме. Ниже — шум, выше — теряются
    # отклонения, где тема названа другими словами. Калибруется на ЭТАПЕ 5.
    deviation_sim_min_score: float = 0.45

    # ──────────────────────────────────────────────────────────────
    # Embeddings (BGE-M3)
    # ──────────────────────────────────────────────────────────────
    # Относительно рабочего каталога. Навыком внутри нанобота путь, если
    # файла тут нет, ищется ещё в его каталоге моделей — см. adopt_agent_models.
    bge_model_path: str = "models/bge-m3-russian-legal"
    bge_batch_size: int = 16
    bge_max_length: int = 512

    # ──────────────────────────────────────────────────────────────
    # Reranker
    # ──────────────────────────────────────────────────────────────
    reranker_model_path: str = "models/bge-reranker-v2-m3"
    reranker_top_n: int = 5
    reranker_enabled: bool = True

    # ──────────────────────────────────────────────────────────────
    # vLLM server params (используется только при старте сервера)
    # ──────────────────────────────────────────────────────────────
    vllm_port: int = 5000
    vllm_gpu_memory_utilisation: float = 0.75
    vllm_tensor_parallel_size: int = 1
    vllm_max_model_len: int = 32768

    # ──────────────────────────────────────────────────────────────
    # Paths
    # ──────────────────────────────────────────────────────────────
    data_raw_dir: str = "data/raw"
    data_md_dir: str = "data/md"
    data_index_dir: str = "data/index"
    models_dir: str = "models"
    logs_dir: str = "logs"

    # ──────────────────────────────────────────────────────────────
    # Extraction (LLM-извлечение отклонений при индексации)
    # ──────────────────────────────────────────────────────────────
    # Сколько чанков отправлять в ОДИН вызов GigaChat.
    # Увеличение с 1 до 5 даёт ~5x ускорение индексации.
    # Для GigaChat: 5 чанков × 1500 симв ≈ 2500 токенов — в пределах лимита.
    extractor_batch_size: int = 5

    # Максимум чанков на документ (после предфильтрации).
    # 40 — достаточно для большинства актов, предотвращает зависание на гигантских.
    extractor_max_chunks: int = 40

    # ──────────────────────────────────────────────────────────────
    # RAG / Search
    # ──────────────────────────────────────────────────────────────
    # Для реальных актов 40-80 страниц рекомендуется chunk_size=1500-2000.
    # Меньше чанков → быстрее индексация и меньше вызовов GigaChat.
    chunk_size: int = 1500
    chunk_overlap: int = 200
    top_k: int = 15
    rrf_k: int = 60

    # ──────────────────────────────────────────────────────────────
    # API server
    # ──────────────────────────────────────────────────────────────
    api_host: str = "0.0.0.0"
    api_port: int = 8501

    # ──────────────────────────────────────────────────────────────
    # Greenplum (общий контур знаний; выключено = локальный режим)
    # ──────────────────────────────────────────────────────────────
    # Адрес, база и схема — значения площадки, в коде их нет: либо
    # `site_defaults.env` / `.env`, либо, навыком внутри нанобота, настройки
    # канала его шины (`channels.postgres.dsn` и `.schema`).
    gp_enabled: bool = False
    gp_host: str = ""
    gp_port: int = 5432
    gp_db: str = ""
    gp_user: str = ""                 # логин УЗ; password='' (доменная аутентификация)
    gp_password: str = ""
    # Схема для НАШИХ таблиц t_fu_*.
    #
    # Это схема экосистемы единого рабочего места: там же лежат таблицы
    # самого рабочего места и шина с наноботом. Коллизии имён нет — у нас
    # свой префикс `t_fu_`. Вердикт обязан быть общим, а права в этой схеме
    # уже у тех же людей, что работают с рабочим местом.
    gp_write_schema: str = ""
    # Схема ЧТЕНИЯ. Пусто — читаем из своей же, и это нормальный случай:
    # когда таблицы лежат там, где у всех есть права, разделять чтение и
    # запись нечего. Представления и функции-посредники тогда не нужны, и
    # `bootstrap_sharing` честно отвечает «раздавать нечего».
    #
    # Непустой она была, пока таблицы стояли в схеме с ограниченным
    # доступом: читали через представления в витринной схеме, писали через
    # функции. Механизм оставлен — он пригодится, если схема снова разъедется
    # с правами, — но по умолчанию выключен.
    gp_read_schema: str = ""
    # Групповая роль читателей витринной схемы — кому выдаются гранты на
    # представления и функции. Пусто — выводится из имени схемы (s… → r…_r).
    gp_reader_role: Optional[str] = None
    # Витрины — только чтение. Имя без схемы значит «представление в нашей же
    # схеме записи»: его один раз создаёт скрипт площадки из репозитория
    # Follow Up (scripts/migrate_to_agent_schema.py)
    # поверх настоящей витрины, и дальше всё читается из одной схемы. Полное
    # имя «схема.витрина» (так в site_defaults.env) — читать витрину напрямую.
    #
    # Витрина поручений
    gp_src_view: str = "v_fu_assignment"
    # Витрина пунктов актов (тексты нарушений) — источник автодогрузки актов,
    # которых нет в корпусе знаний
    gp_act_vitrina_view: str = "v_fu_act_violation"
    # Автодогрузка недостающих актов из витрины
    fu_backfill_enabled: bool = True
    fu_backfill_batch: int = 8        # актов за один фоновый проход

    # ──────────────────────────────────────────────────────────────
    # BitBucket (репозитории проверок; read-only)
    # ──────────────────────────────────────────────────────────────
    # Пусто — блок «Репозиторий» выключен. Значения площадки — в
    # site_defaults.env; навыку внутри нанобота блок не нужен: личный токен
    # на общем сервере не годится.
    bitbucket_base_url: str = ""
    bitbucket_project: str = ""
    bitbucket_token: str = ""         # HTTP access token (Bearer), права Read

    # ──────────────────────────────────────────────────────────────
    # Скилл «Контроль исполнения поручений»
    # ──────────────────────────────────────────────────────────────
    exec_control_enabled: bool = True
    upload_max_mb: int = 15
    # Ленивый синк витрины поручений
    fu_sync_interval_min: int = 30    # период фоновой проверки дельты
    fu_sync_lease_min: int = 15       # TTL lease-лока
    fu_sync_batch: int = 50           # строк на батч эмбеддинга
    # Чанкование текстов поручений (поля короткие — см. разведку)
    poruch_chunk_chars: int = 1200
    poruch_chunk_overlap: int = 150

    # ──────────────────────────────────────────────────────────────
    # Derived paths (computed from string settings above)
    # ──────────────────────────────────────────────────────────────
    @property
    def base_dir(self) -> Path:
        return Path(__file__).resolve().parent.parent

    @property
    def raw_dir(self) -> Path:
        return self.base_dir / self.data_raw_dir

    @property
    def md_dir(self) -> Path:
        return self.base_dir / self.data_md_dir

    @property
    def index_dir(self) -> Path:
        return self.base_dir / self.data_index_dir

    @property
    def faiss_file(self) -> Path:
        return self.index_dir / "index.faiss"

    @property
    def bm25_file(self) -> Path:
        return self.index_dir / "bm25.pkl"

    @property
    def db_file(self) -> Path:
        return self.index_dir / "followup.db"

    @property
    def deviations_file(self) -> Path:
        return self.index_dir / "deviations.json"

    @property
    def log_dir(self) -> Path:
        return self.base_dir / self.logs_dir

    @property
    def models_path(self) -> Path:
        return self.base_dir / self.models_dir


# ──────────────────────────────────────────────────────────────────
# Singleton
# ──────────────────────────────────────────────────────────────────
_settings: Optional[Settings] = None


def get_settings() -> Settings:
    global _settings
    if _settings is None:
        _settings = Settings()
    return _settings
