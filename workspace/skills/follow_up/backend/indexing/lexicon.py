"""Follow Up 2.0 — единственный токенизатор корпуса.

Сегодня их два: `index_builder.tokenize` и его дословная копия
`retrieval._tokenize` с комментарием «копируем для консистентности». Копия —
это обещание синхронности, которое некому выполнять: любая правка одного
разъедет токенизацию запроса и токенизацию индекса МОЛЧА, и поиск начнёт
терять документы без единой ошибки в логах.

Плюс стеммер. Без него «лимитов» и «лимит» — разные термы, а вопрос аудитора и
текст акта почти никогда не совпадают по форме слова. Стеммер здесь свой,
правиловый: pymorphy/snowball в закрытом контуре может не быть, а падать из-за
отсутствия зависимости поиск не должен. Правила покрывают падежи и числа
существительных и прилагательных — этого хватает для доменной лексики
(«лимит», «карта», «превышение», «клиентский»).

`LEXICON_VERSION` пишется в пикл BM25: после смены правил корпус и запрос
обязаны токенизироваться одинаково, иначе индекс станет смешанным — часть
документов по старым правилам, часть по новым.
"""
from __future__ import annotations

import re
from typing import List

# Версия правил. Меняется ЛЮБОЙ правкой ниже — по ней índex_builder понимает,
# что пикл собран другим токенизатором и его надо пересобрать.
LEXICON_VERSION = 3

_WORD_RE = re.compile(r"[а-яёa-z0-9]+")

# Окончания по убыванию длины: сначала пробуем длинные, иначе «лимитами» → «лимитам»
_SUFFIXES = (
    # прилагательные
    "ейшими", "ейшего", "ейшему", "ыми", "ими", "ого", "ему", "ому", "ых", "их",
    "ая", "яя", "ое", "ее", "ой", "ей", "ый", "ий", "ым", "им", "ую", "юю",
    # существительные
    "ами", "ями", "ах", "ях", "ов", "ев", "ий", "ью", "ия", "ие", "ей",
    "ам", "ям", "ом", "ем", "ой", "ей", "ы", "и", "а", "я", "о", "е", "у", "ю",
)

# Аббревиатуры и термины, у которых нет словоформ: резать нечего, а обрубок
# ломал бы поиск. Слова, у которых формы ЕСТЬ, сюда попадать не должны:
# «карта» в списке при отсутствующей «карты» дала бы карта→карта, карты→карт,
# то есть формы одного слова разъехались бы — ровно то молчаливое расхождение,
# против которого написан модуль. Проверяется тестом на согласованность форм.
_KEEP = frozenset({
    "смс", "sms", "km", "км", "sql", "бд", "ит", "дбо", "абс", "аис", "цфт",
    "аml", "aml", "kyc", "пвк", "офд", "црм", "crm", "api",
})

# Минимальная длина ОСТАТКА. Ограничение на длину входа было бы ошибкой:
# «акта» (4) осталось бы нетронутым, а «актов» (5) обрезалось до «акт» — формы
# одного слова разъехались бы.
_MIN_STEM = 3


def stem(word: str) -> str:
    """Словоформа → общий для всех форм терм.

    Стрижётся ДО НЕПОДВИЖНОЙ ТОЧКИ, а не за один проход. Причина: валидный
    остаток сам может кончаться на окончание. «системы» за один проход даёт
    «систем», а базовая форма «систем» — «сист», и два написания одного слова
    попадают в разные термы. Повтор до стабилизации сводит обе к «сист».

    Идемпотентность — обязательное свойство: stem(stem(w)) == stem(w).
    """
    if word in _KEEP or word.isdigit():
        return word
    prev = None
    cur = word
    while cur != prev:
        prev = cur
        for suf in _SUFFIXES:
            if cur.endswith(suf) and len(cur) - len(suf) >= _MIN_STEM:
                cur = cur[: -len(suf)]
                break
    return cur


def tokenize(text: str, stem_words: bool = True) -> List[str]:
    """Текст → термы. ЕДИНСТВЕННАЯ точка: и корпус, и запрос идут через неё."""
    if not text:
        return []
    words = _WORD_RE.findall(text.lower())
    if not stem_words:
        return [w for w in words if len(w) > 1]
    return [stem(w) for w in words if len(w) > 1]


def content_terms(text: str) -> List[str]:
    """Термы запроса без повторов — вход для метрик покрытия."""
    seen, out = set(), []
    for t in tokenize(text):
        if t not in seen:
            seen.add(t)
            out.append(t)
    return out
